export const DICTS: Record<Lang, Dict> = { uz, ru, en };

export function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('lang');
    if (saved === 'uz' || saved === 'ru' || saved === 'en') return saved;
  } catch {
    /* storage may be blocked */
  }
  const nav = (navigator.language || 'uz').slice(0, 2);
  return nav === 'ru' ? 'ru' : nav === 'en' ? 'en' : 'uz';
}

export const I18n = createContext<{ t: Dict; lang: Lang; setLang: (l: Lang) => void }>({ t: uz, lang: 'uz', setLang: () => {} });
export const useT = () => useContext(I18n);
